import assert from "node:assert/strict";
import { emptyData, migrateChatWorkspaces, createSolarStore } from "../src/services/storageCore.ts";
import { ToolRegistry, ToolExecutor } from "../src/services/toolRegistry.ts";
import { runCortexTools } from "../src/lib/cortex/tool-runtime.ts";
import { solarAgentStore } from "../src/services/solarAgentStore.ts";
import { initializeAccountScope } from "../src/services/accountScope.ts";
import { toolApprovals } from "../src/services/toolApprovals.ts";

const original = emptyData();
original.conversations = [{ id: "legacy", space: "work", title: "Mon projet", modelId: "m", effort: "high", createdAt: "2026-10-01", updatedAt: "2026-10-01" }];
original.messages = [{ id: "message", conversationId: "legacy", content: "Original", role: "user", status: "completed", order: 0 }];
original.drafts = [{ conversationId: "legacy", text: "Brouillon conservé", attachments: [] }];
const migrated = migrateChatWorkspaces(original);
assert.equal(original.conversations[0].space, "work", "migration non destructive");
assert.equal(migrated.conversations[0].space, "chat");
assert.equal(migrated.conversations[0].development, true);
assert.deepEqual(migrated.messages, original.messages);
assert.deepEqual(migrated.drafts, original.drafts);
assert.equal(migrateChatWorkspaces(migrated), migrated, "migration idempotente");
let disk = structuredClone(original), writes = 0;
const store = createSolarStore({ read: async () => structuredClone(disk), write: async value => { disk = structuredClone(value); writes++; } });
assert.equal((await store.listConversations())[0].id, "legacy");
assert.equal(writes, 1, "migration persistée avant exposition");
assert.equal((await createSolarStore({ read: async () => structuredClone(disk), write: async () => { throw Error("migration répétée"); } }).listMessages("legacy"))[0].content, "Original");
const failing = createSolarStore({ read: async () => structuredClone(original), write: async () => { throw Error("disque plein"); } });
await assert.rejects(failing.listConversations(), /disque plein/);
assert.equal(original.conversations[0].space, "work");

let turnDisk = emptyData(), failTurn = false;
const turnStore = createSolarStore({ read: async () => structuredClone(turnDisk), write: async value => { if (failTurn) throw Error("disque plein"); turnDisk = structuredClone(value); } });
await turnStore.listConversations(); failTurn = true;
const conversation = { id: "atlas-turn", space: "agent", title: "Atlas", effort: "medium", createdAt: "2026-10-21", updatedAt: "2026-10-21" };
const user = { id: "turn-user", conversationId: conversation.id, role: "user", content: "Texte", status: "completed", order: 0 };
const assistant = { ...user, id: "turn-assistant", role: "assistant", content: "", status: "streaming", order: 1 };
await assert.rejects(turnStore.saveTurn(conversation, user, assistant), /disque plein/);
assert.equal(turnDisk.messages.length, 0); assert.equal((await turnStore.listConversations()).length, 0, "aucun tour partiellement enregistré");
failTurn = false; await turnStore.saveTurn(conversation, user, assistant);
assert.equal(turnDisk.messages.length, 2); assert.equal(turnDisk.conversations.length, 1);

const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
initializeAccountScope("phase-one-alice");
const legacyAgent = { id: "old-agent", ownerId: "phase-one-alice", name: "Ancien agent", description: "", instructions: "Anciennes consignes", providerId: "p", modelId: "m", effort: "high", enabled: true, grants: ["gmail.read"], skillIds: [], memoryEnabled: true, createdAt: "2026-10-01", updatedAt: "2026-10-01" };
await solarAgentStore.saveAgent(legacyAgent);
const first = await solarAgentStore.ensureAtlas({ providerId: "p", modelId: "m", effort: "medium" });
assert.deepEqual(await solarAgentStore.ensureAtlas({ providerId: "other", modelId: "other", effort: "ultra" }), first);
const data = await solarAgentStore.snapshot();
assert.deepEqual(data.agents.find(agent => agent.id === legacyAgent.id), legacyAgent);
assert.deepEqual(data.agents.find(agent => agent.id === first.agentId).grants, [], "pas d'héritage implicite de permissions");
await assert.rejects(solarAgentStore.deleteAgent(first.agentId), /assistant principal/);
initializeAccountScope("phase-one-bob");
assert.equal((await solarAgentStore.snapshot()).agents.length, 0);

const registry = new ToolRegistry(); let executed = 0, currentAccount = true, approved = 0;
const parameters = { type: "object", properties: { query: { type: "string", minLength: 1, maxLength: 50 } }, required: ["query"], additionalProperties: false };
registry.register({ name: "fixture.read", pluginId: "fixture", description: "Lire une source", parameters, permissions: ["fixture.read"], risk: "read", execute: async () => { executed++; return { content: "Une donnée réelle du faux service de test" }; } });
registry.register({ name: "fixture.send", pluginId: "fixture", description: "Envoyer", parameters, permissions: ["fixture.write"], risk: "publish", externalEffects: true, execute: async () => { executed++; return "envoyé"; } });
const executor = new ToolExecutor(registry), signal = new AbortController().signal;
const context = { account: "alice", isCurrentAccount: () => currentAccount, verifyConnection: async () => "fixture-account", approve: async request => { approved++; assert.equal(request.account, "fixture-account"); return true; } };
await assert.rejects(executor.run("fixture.read", { query: "x", extra: true }, new Set(["fixture.read"]), signal, context), /Paramètres/);
assert.equal(executed, 0);
await assert.rejects(executor.run("fixture.send", { query: "x" }, new Set(["fixture.write"]), signal), /Autorisation|autorisation/);
assert.equal(executed, 0, "une permission ne remplace pas une approbation d'envoi");
await executor.run("fixture.send", { query: "x" }, new Set(["fixture.write"]), signal, context);
assert.equal(approved, 1);
await executor.run("fixture.read", { query: "x" }, new Set(["fixture.read"]), signal, { ...context, cloudProvider: "Cloud de test" });
assert.equal(approved, 2, "transfert cloud approuvé même en lecture");
const count = executed;
await assert.rejects(executor.run("fixture.send", { query: "x" }, new Set(["fixture.write"]), signal, { ...context, approve: async () => { currentAccount = false; return true; } }), /compte Solar/);
assert.equal(executed, count, "changement de compte pendant l'approbation"); currentAccount = true;
const stopped = new AbortController();
const approval = toolApprovals.request({ tool: "fixture.read", plugin: "fixture", account: "alice", description: "Lire", input: { query: "x" }, risk: "read" }, stopped.signal);
assert.equal(toolApprovals.snapshot().length, 1); stopped.abort(); assert.equal(await approval, false); assert.equal(toolApprovals.snapshot().length, 0);

const tools = [{ name: "fixture.read", pluginId: "fixture", description: "Lire", parameters }];
let turns = [JSON.stringify({ tool: "fixture.read", arguments: { query: "x" } }), JSON.stringify({ answer: "Une source trouvée." })];
const services = { generate: async () => ({ text: turns.length>1?turns.shift():turns[0], stopReason: "stop" }), execute: async () => ({ content: "source" }) };
const result = await runCortexTools({ prompt: "Lis ma source", signal, tools, requiredPlugins: ["fixture"] }, services);
assert.equal(result.calls.length, 1); assert.equal(result.answer, "Une source trouvée.");
turns = [JSON.stringify({ answer: "Tout est fait" })];
await assert.rejects(runCortexTools({ prompt: "Lis ma source", signal, tools, requiredPlugins: ["fixture"] }, services), /Résultats manquants/);
turns = [JSON.stringify({ tool: "secret.read", arguments: { query: "x" } })];
await assert.rejects(runCortexTools({ prompt: "Lis", signal, tools }, services), /non exposé/);
turns = Array(2).fill(JSON.stringify({ tool: "fixture.read", arguments: { query: "x" } }));
await assert.rejects(runCortexTools({ prompt: "Lis", signal, tools }, services), /ne progresse plus/);
turns = ['{"tool":'];
await assert.rejects(runCortexTools({ prompt: "Lis", signal, tools }, services), /après correction/);
console.log("Phase 1 : migrations, isolation, approbations et boucle Cortex — PASS (services de test simulés).");
