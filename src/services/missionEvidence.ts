import type {CortexToolCall} from '../lib/cortex/tool-runtime.ts';
function stable(value:unknown):unknown{
 if(Array.isArray(value))return value.map(stable);
 if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).sort(([a],[b])=>a.localeCompare(b)).map(([key,v])=>[key,stable(v)]));
 return value;
}
/** Hash actual source observations, never LLM prose. A failed/partial run cannot
 * advance a watch's last successful digest. No raw mail is copied to the watch. */
export async function evidenceDigest(calls:CortexToolCall[],context?:unknown):Promise<string|undefined>{
 const reads=calls.filter(c=>!c.externalEffects&&c.result!=='[not retained]');if(!reads.length)return;
 const observations=reads.map(c=>{let value:unknown;try{value=JSON.parse(c.result);}catch{value=c.result;}if(value&&typeof value==='object'&&!Array.isArray(value)&&['github.profile_activity','github.repository_activity'].includes(c.tool)){
  value={...value as Record<string,unknown>};delete (value as Record<string,unknown>).observedAt;
  // These two fields are a rolling query window generated by Solar, not a
  // resource modification. Explicit periods remain represented in arguments.
  if(c.tool==='github.profile_activity'&&!c.arguments.from&&!c.arguments.to)delete (value as Record<string,unknown>).period;
 }return {tool:c.tool,arguments:stable(c.arguments),result:stable(value)};}).sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b)));
 const text=JSON.stringify(context===undefined?observations:{observations,context:stable(context)});
 return [...new Uint8Array(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(text)))].map(x=>x.toString(16).padStart(2,'0')).join('');
}
export function watchOutcome(previous:{lastEvidenceDigest?:string;notifyOn?:'always'|'changes'},mission:{status:string;evidenceDigest?:string},at=new Date().toISOString()){
 if(mission.status!=='completed')return {notify:true,update:{lastCheckedAt:at}};
 if(previous.notifyOn!=='changes')return {notify:true,update:{lastCheckedAt:at,...(mission.evidenceDigest?{lastEvidenceDigest:mission.evidenceDigest}:{})}};
 if(!mission.evidenceDigest)return {notify:true,update:{lastCheckedAt:at},error:'Aucune source structurée attestée : comparaison des changements indisponible.'};
 const notify=previous.lastEvidenceDigest!==undefined&&previous.lastEvidenceDigest!==mission.evidenceDigest;
 return {notify,update:{lastCheckedAt:at,lastEvidenceDigest:mission.evidenceDigest,...(notify?{lastNotifiedAt:at}:{})}};
}
